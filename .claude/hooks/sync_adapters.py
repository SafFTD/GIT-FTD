#!/usr/bin/env python3
"""Regenerate tool-specific stubs from the neutral workflows/*.md.

Single source of truth: workflows/<name>.md.
For each, (re)write:
  - .claude/commands/<name>.md   — Claude Code slash command stub
  - .agent/workflows/<name>.md   — Antigravity workflow stub

Both stubs are thin: they carry a description and point back at the neutral
procedure. Stubs whose neutral workflow no longer exists are removed.

This script ONLY writes under .claude/commands/ and .agent/workflows/. It never
edits workflows/, AGENTS.md, or .claude/memory/. Safe to run repeatedly
(idempotent) — it's wired to a PostToolUse hook and to `/sync`.
"""
from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
WORKFLOWS = ROOT / "workflows"
CLAUDE_CMDS = ROOT / ".claude" / "commands"
AGENT_WFS = ROOT / ".agent" / "workflows"

# Workflows that take a free-text argument (feature/bug description, F<N>, etc.)
ARG_HINTS = {
    "plan": "<feature or bug description>",
    "ship": "<optional F<N> or B<N>>",
    "remember": "<the learning to save>",
    "save-note": "<the note>",
}


def describe(md_path: pathlib.Path) -> str:
    """First real summary paragraph: skip the '# Workflow:' heading and the
    leading '>' blockquote, take the next non-empty line."""
    for line in md_path.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s or s.startswith("#") or s.startswith(">"):
            continue
        return s
    return f"Run the {md_path.stem} workflow."


def claude_stub(name: str, desc: str) -> str:
    fm = [f"description: {desc}"]
    if name in ARG_HINTS:
        fm.append(f"argument-hint: {ARG_HINTS[name]}")
    front = "\n".join(fm)
    arg_line = "\n\nArguments:\n\n$ARGUMENTS\n" if name in ARG_HINTS else "\n"
    return (
        "<!-- AUTO-GENERATED by .claude/hooks/sync_adapters.py — DO NOT EDIT.\n"
        f"     Edit the neutral procedure: workflows/{name}.md, then run /sync. -->\n"
        f"---\n{front}\n---\n"
        f"\nFollow the neutral procedure in `workflows/{name}.md`. It is the single "
        "source of truth shared by Claude and Antigravity; do exactly what it says."
        f"{arg_line}"
    )


def agent_stub(name: str, desc: str) -> str:
    return (
        "<!-- AUTO-GENERATED by .claude/hooks/sync_adapters.py — DO NOT EDIT.\n"
        f"     Edit the neutral procedure: workflows/{name}.md, then run sync. -->\n"
        f"# {name}\n\n{desc}\n\n"
        f"Follow the neutral procedure in `../workflows/{name}.md` (relative to the "
        "repo root: `workflows/" + name + ".md`). It is the single source of truth "
        "shared by Antigravity and Claude; do exactly what it says.\n"
    )


def sync() -> int:
    if not WORKFLOWS.is_dir():
        print(f"sync_adapters: no workflows/ dir at {WORKFLOWS}", file=sys.stderr)
        return 0
    CLAUDE_CMDS.mkdir(parents=True, exist_ok=True)
    AGENT_WFS.mkdir(parents=True, exist_ok=True)

    names = sorted(p.stem for p in WORKFLOWS.glob("*.md"))
    for name in names:
        desc = describe(WORKFLOWS / f"{name}.md")
        (CLAUDE_CMDS / f"{name}.md").write_text(claude_stub(name, desc), encoding="utf-8")
        (AGENT_WFS / f"{name}.md").write_text(agent_stub(name, desc), encoding="utf-8")

    # Remove orphan stubs (neutral workflow deleted/renamed).
    valid = set(names)
    removed = []
    for d in (CLAUDE_CMDS, AGENT_WFS):
        for stub in d.glob("*.md"):
            if stub.stem not in valid:
                stub.unlink()
                removed.append(str(stub.relative_to(ROOT)))

    print(f"sync_adapters: generated {len(names)} stub(s) "
          f"({', '.join(names)}); removed {len(removed)} orphan(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(sync())
